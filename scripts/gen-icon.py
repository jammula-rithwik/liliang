#!/usr/bin/env python3
"""Generate Lìliàng's adaptive launcher icon and splash mark.

The 力 ("strength") glyph is traced from Ma Shan Zheng, the same brush hand
the app sets its hanzi in, and laid into the 108dp adaptive-icon viewport:

  - ic_launcher_background.xml   vermillion lacquer field with faint
                                 auspicious-cloud (祥云) scrolls in the corners
  - ic_launcher_foreground.xml   gold double seal border + bone brush 力
  - ic_launcher_monochrome.xml   glyph alone, for Android 13+ themed icons
  - splash_mark.xml              round seal for the Android 12+ splash screen

Usage:  python scripts/gen-icon.py [path/to/MaShanZheng.ttf]
Defaults to the subset face committed under res/font/ (力 is in it).
"""

import math
import sys
from pathlib import Path

from fontTools.misc.transform import Transform
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app" / "src" / "main" / "res"

GLYPH_CHAR = "力"
VIEWPORT = 108.0
BONE = "#F1E8D6"
GOLD = "#D9B44A"
VERMILLION = "#C73E2E"
VERMILLION_DEEP = "#8E2519"
LACQUER_HI = "#D9523E"


def glyph_path(font_path: Path, char: str, box: float, cx_t: float, cy_t: float) -> str:
    font = TTFont(str(font_path))
    name = font.getBestCmap()[ord(char)]
    glyph_set = font.getGlyphSet()
    glyph = glyph_set[name]
    bounds = BoundsPen(glyph_set)
    glyph.draw(bounds)
    x_min, y_min, x_max, y_max = bounds.bounds
    scale = box / max(x_max - x_min, y_max - y_min)
    cx = (x_min + x_max) / 2
    cy = (y_min + y_max) / 2
    transform = Transform(scale, 0, 0, -scale, cx_t - cx * scale, cy_t + cy * scale)
    pen = SVGPathPen(glyph_set, ntos=lambda f: f"{f:.2f}")
    glyph.draw(TransformPen(pen, transform))
    return pen.getCommands()


def vector(body: str, size: float = VIEWPORT) -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by scripts/gen-icon.py — edit the script, not this file. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        f'    android:width="{size:.0f}dp"\n'
        f'    android:height="{size:.0f}dp"\n'
        f'    android:viewportWidth="{size:.0f}"\n'
        f'    android:viewportHeight="{size:.0f}">\n'
        f"{body}"
        "</vector>\n"
    )


def path(d: str, fill: str | None = None, stroke: str | None = None, width: float = 0,
         alpha: float = 1.0, cap: str | None = None) -> str:
    attrs = [f'android:pathData="{d}"']
    if fill:
        attrs.append(f'android:fillColor="{fill}"')
        if alpha < 1:
            attrs.append(f'android:fillAlpha="{alpha:.2f}"')
    if stroke:
        attrs.append(f'android:strokeColor="{stroke}"')
        attrs.append(f'android:strokeWidth="{width:.2f}"')
        if alpha < 1:
            attrs.append(f'android:strokeAlpha="{alpha:.2f}"')
        if cap:
            attrs.append(f'android:strokeLineCap="{cap}"')
    return "    <path " + "\n        ".join(attrs) + "/>\n"


def rounded_square(side: float, radius: float, c: float = VIEWPORT / 2) -> str:
    lo = c - side / 2
    hi = c + side / 2
    r = radius
    return (
        f"M{lo + r:.2f},{lo:.2f} L{hi - r:.2f},{lo:.2f} Q{hi:.2f},{lo:.2f} {hi:.2f},{lo + r:.2f} "
        f"L{hi:.2f},{hi - r:.2f} Q{hi:.2f},{hi:.2f} {hi - r:.2f},{hi:.2f} "
        f"L{lo + r:.2f},{hi:.2f} Q{lo:.2f},{hi:.2f} {lo:.2f},{hi - r:.2f} "
        f"L{lo:.2f},{lo + r:.2f} Q{lo:.2f},{lo:.2f} {lo + r:.2f},{lo:.2f} Z"
    )


def cloud(x: float, y: float, s: float, flip: bool = False) -> str:
    """One xiangyun scroll: a spiral head trailing a tail, as a stroke path."""
    pts = []
    # Archimedean spiral head
    turns = 1.6
    steps = 28
    for i in range(steps + 1):
        t = i / steps
        a = t * turns * 2 * math.pi
        r = s * (0.15 + 0.85 * t) * 0.5
        px = x + r * math.cos(a) * (-1 if flip else 1)
        py = y + r * math.sin(a)
        pts.append((px, py))
    # trailing tail sweeping out
    ex, ey = pts[-1]
    d = f"M{pts[0][0]:.2f},{pts[0][1]:.2f} " + " ".join(f"L{px:.2f},{py:.2f}" for px, py in pts[1:])
    dx = s * 1.4 * (-1 if flip else 1)
    d += f" Q{ex + dx * 0.5:.2f},{ey + s * 0.35:.2f} {ex + dx:.2f},{ey:.2f}"
    return d


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else RES / "font" / "ma_shan_zheng.ttf"
    c = VIEWPORT / 2

    # ── background: lacquer with a soft top highlight and corner clouds ──
    bg = path("M0,0 H108 V108 H0 Z", fill=VERMILLION)
    bg += path("M0,0 H108 V40 Q54,52 0,40 Z", fill=LACQUER_HI, alpha=0.35)
    bg += path("M0,70 Q54,58 108,70 V108 H0 Z", fill=VERMILLION_DEEP, alpha=0.45)
    for (x, y, s, f) in [(14, 16, 12, False), (94, 92, 12, True), (92, 18, 9, True), (16, 90, 9, False)]:
        bg += path(cloud(x, y, s, f), stroke=GOLD, width=1.1, alpha=0.22, cap="round")

    # ── foreground: gold double seal border, brush 力 inside the safe zone ──
    glyph = glyph_path(src, GLYPH_CHAR, 33.0, c + 1.0, c + 0.5)
    mono_glyph = glyph_path(src, GLYPH_CHAR, 44.0, c + 1.0, c + 0.5)
    fg = path(rounded_square(47, 9), stroke=GOLD, width=1.8, alpha=0.95)
    fg += path(rounded_square(42.5, 6.5), stroke=GOLD, width=0.7, alpha=0.6)
    fg += path(glyph, fill=BONE)

    mono = path(mono_glyph, fill="#FFFFFFFF")

    # ── splash: round seal with the glyph, fits the 2/3 splash mask ──
    splash = path(f"M{c},{c - 34} A34,34 0 1,1 {c - 0.01},{c - 34} Z", fill=VERMILLION)
    splash += path(f"M{c},{c - 30} A30,30 0 1,1 {c - 0.01},{c - 30} Z", stroke=GOLD, width=1.4, alpha=0.9)
    splash += path(glyph_path(src, GLYPH_CHAR, 32.0, c + 1.0, c + 0.5), fill=BONE)

    drawable = RES / "drawable"
    drawable.mkdir(parents=True, exist_ok=True)
    (drawable / "ic_launcher_background.xml").write_text(vector(bg), encoding="utf-8")
    (drawable / "ic_launcher_foreground.xml").write_text(vector(fg), encoding="utf-8")
    (drawable / "ic_launcher_monochrome.xml").write_text(vector(mono), encoding="utf-8")
    (drawable / "splash_mark.xml").write_text(vector(splash), encoding="utf-8")
    print("wrote launcher + splash drawables")


if __name__ == "__main__":
    main()
